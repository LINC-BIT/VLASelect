#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EVAL_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"

DATE=$(date +"%Y-%m-%d")
TIME=$(date +"%H-%M-%S")
LOG_DIR="train/octo/ricl/nohup_out/$DATE"
LOG_FILE="$LOG_DIR/$TIME.log"
mkdir -p "$LOG_DIR"

CUDA_DEVICES=${CUDA_DEVICES:-0}
EXP_NAME=${EXP_NAME:-}
TAIL_LOG=${TAIL_LOG:-1}
LAUNCH_DIRECT=${LAUNCH_DIRECT:-0}
RICL_SMOKE=${RICL_SMOKE:-1}
LOG_FILE=${LOG_FILE_OVERRIDE:-$LOG_FILE}
ENV_ID=${ENV_ID_OVERRIDE:-PickCubeObjectScaleUp1p2-v1}
ENVS_ID=${ENVS_ID_OVERRIDE:-"['PickCubeObjectScaleUp1p2-v1']"}
ENV_CHANGE_TIME_POINTS=${ENV_CHANGE_TIME_POINTS_OVERRIDE:-"[1000000]"}
ENV_CONFIG_PATH=${ENV_CONFIG_PATH_OVERRIDE:-datasets/PickCube-v1/motionplanning/trajectory.rgb+depth+state_dict.pd_ee_delta_pos.physx_cpu.json}
STATE_NORM_STATS_PATH=${STATE_NORM_STATS_PATH_OVERRIDE:-ckpt/PickCube-v1/ours/octo/PickCube-v1-state-max-min.pth}
CHECKPOINT_PATH=${PRETRAINED_CHECKPOINT_PATH:-ckpt/PickCube-v1/ours/octo/pretrain_large_model_ppo/20260201-183518-lr3e-4/checkpoints/best_success_once-copy.pt}
TOTAL_TIMESTEPS=${TOTAL_STEPS_OVERRIDE:-${TOTAL_STEPS:-5000000}}
NUM_ENVS=${NUM_ENVS_OVERRIDE:-${NUM_ENVS:-128}}
NUM_EVAL_ENVS=${NUM_EVAL_ENVS_OVERRIDE:-${NUM_EVAL_ENVS:-8}}
NUM_STEPS=${ROLLOUT_STEPS_OVERRIDE:-${ROLLOUT_STEPS:-16}}
NUM_EVAL_STEPS=${NUM_EVAL_STEPS_OVERRIDE:-${MAX_EPISODE_STEPS_OVERRIDE:-${MAX_EPISODE_STEPS:-50}}}
NUM_MINIBATCHES=${NUM_MINIBATCHES_OVERRIDE:-4}
UPDATE_EPOCHS=${UPDATE_EPOCHS_OVERRIDE:-${UPDATE_EPOCHS:-4}}
MAX_TIME=${MAX_RUNTIME_MINUTES_OVERRIDE:-}
RICL_BANK_CAPACITY=${RICL_BANK_CAPACITY:-4096}
RICL_BANK_ADD_PER_ITER=${RICL_BANK_ADD_PER_ITER:-128}
RICL_NUM_NEIGHBORS=${RICL_NUM_NEIGHBORS:-4}
RICL_RETRIEVAL_TEMPERATURE=${RICL_RETRIEVAL_TEMPERATURE:-10.0}
RICL_STATE_DIM_CAP=${RICL_STATE_DIM_CAP:-32}
RICL_CONTEXT_HIDDEN_DIM=${RICL_CONTEXT_HIDDEN_DIM:-128}
RICL_PROMPT_FEATURE_SCALE=${PROMPT_FEATURE_SCALE:-${RICL_PROMPT_FEATURE_SCALE:-0.12}}

if [ "$RICL_SMOKE" = "1" ]; then
    TOTAL_TIMESTEPS=${TOTAL_STEPS_OVERRIDE:-512}
    NUM_ENVS=${NUM_ENVS_OVERRIDE:-4}
    NUM_EVAL_ENVS=${NUM_EVAL_ENVS_OVERRIDE:-4}
    NUM_STEPS=${ROLLOUT_STEPS_OVERRIDE:-4}
    NUM_EVAL_STEPS=${NUM_EVAL_STEPS_OVERRIDE:-50}
    NUM_MINIBATCHES=${NUM_MINIBATCHES_OVERRIDE:-2}
    UPDATE_EPOCHS=${UPDATE_EPOCHS_OVERRIDE:-1}
fi

EXTRA_ENV=(
    CUDA_DEVICES="$CUDA_DEVICES"
    EXP_NAME="$EXP_NAME"
    LAUNCH_DIRECT="$LAUNCH_DIRECT"
    TAIL_LOG="$TAIL_LOG"
    ENV_ID_OVERRIDE="$ENV_ID"
    ENVS_ID_OVERRIDE="$ENVS_ID"
    ENV_CHANGE_TIME_POINTS_OVERRIDE="$ENV_CHANGE_TIME_POINTS"
    ENV_CONFIG_PATH_OVERRIDE="$ENV_CONFIG_PATH"
    STATE_NORM_STATS_PATH_OVERRIDE="$STATE_NORM_STATS_PATH"
    CHECKPOINT_PATH_OVERRIDE="$CHECKPOINT_PATH"
    TOTAL_TIMESTEPS_OVERRIDE="$TOTAL_TIMESTEPS"
    NUM_ENVS_OVERRIDE="$NUM_ENVS"
    NUM_EVAL_ENVS_OVERRIDE="$NUM_EVAL_ENVS"
    NUM_STEPS_OVERRIDE="$NUM_STEPS"
    NUM_EVAL_STEPS_OVERRIDE="$NUM_EVAL_STEPS"
    NUM_MINIBATCHES_OVERRIDE="$NUM_MINIBATCHES"
    UPDATE_EPOCHS_OVERRIDE="$UPDATE_EPOCHS"
    ENABLE_RICL_INJECTION=${ENABLE_RICL_INJECTION:-1}
    RICL_BANK_CAPACITY="$RICL_BANK_CAPACITY"
    RICL_BANK_ADD_PER_ITER="$RICL_BANK_ADD_PER_ITER"
    RICL_NUM_NEIGHBORS="$RICL_NUM_NEIGHBORS"
    RICL_RETRIEVAL_TEMPERATURE="$RICL_RETRIEVAL_TEMPERATURE"
    RICL_STATE_DIM_CAP="$RICL_STATE_DIM_CAP"
    RICL_CONTEXT_HIDDEN_DIM="$RICL_CONTEXT_HIDDEN_DIM"
    RICL_PROMPT_FEATURE_SCALE="$RICL_PROMPT_FEATURE_SCALE"
)

if [ -n "$MAX_TIME" ]; then
    EXTRA_ENV+=(MAX_TIME_OVERRIDE="$MAX_TIME")
fi

RUN_CMD=(bash "${EVAL_ROOT}/train/octo/ours_single_agent/online_rl_ours_single_agent_cl.sh")

if [ "$LAUNCH_DIRECT" = "1" ]; then
    cd "$EVAL_ROOT"
    exec env "${EXTRA_ENV[@]}" "${RUN_CMD[@]}"
else
    cd "$EVAL_ROOT"
    nohup env "${EXTRA_ENV[@]}" "${RUN_CMD[@]}" > "$LOG_FILE" 2>&1 &
    TRAIN_PID=$!
    echo "TRAIN_PID=$TRAIN_PID"
    echo "RUN_DIR=ckpt/$EXP_NAME/[agent]"
    echo "LOG_FILE=$LOG_FILE"
    if [ "$TAIL_LOG" = "1" ]; then
        tail --pid="$TRAIN_PID" -f "$LOG_FILE"
    fi
fi
